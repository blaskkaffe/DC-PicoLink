#!/bin/bash
# Builds the one-file DreamPi installer from host/dreampi/:
#     tools/make-dreampi-setup.sh [output]      (default: dist/dc-picolink-dreampi-setup.sh)
# The output is a bash script with host/dreampi/ attached as a tar.gz (base64);
# on the Pi it unpacks itself and runs install.sh. Release builds attach it.
set -eu
cd "$(dirname "$0")/.."
out=${1:-dist/dc-picolink-dreampi-setup.sh}
mkdir -p "$(dirname "$out")"
{
cat <<'HDR'
#!/bin/bash
# DC-PicoLink: installs the DreamPi side (serial /dev/dccable, W5500 network dcusb0
# = 192.168.99.1 with DHCP + NAT + Dreamcast Live VPN address, SD card server dcsd).
# Self-contained: copy this one file to the Pi and run
#     sudo bash dc-picolink-dreampi-setup.sh
# Safe to run again (updates the files; keeps your own /etc/dcusb0.conf and /etc/dcsd.conf).
# Generated by tools/make-dreampi-setup.sh from host/dreampi/ - edit those, not this.
set -eu
[ "$(id -u)" = 0 ] || { echo "run with sudo: sudo bash $0" >&2; exit 1; }
for c in tar base64 gzip; do command -v $c >/dev/null || { echo "missing $c" >&2; exit 1; }; done
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
sed -n '/^__PAYLOAD_BELOW__$/,$p' "$0" | tail -n +2 | base64 -d | tar xzf - -C "$tmp"
chmod +x "$tmp"/dreampi/*.sh "$tmp"/dreampi/dcsd-* "$tmp"/dreampi/dcsd.py "$tmp"/dreampi/dcusb0-vpn
bash "$tmp/dreampi/install.sh"
exit 0
__PAYLOAD_BELOW__
HDR
tar --owner=0 --group=0 --sort=name --mtime='2000-01-01' -C host -czf - dreampi | base64 -w 76
} > "$out"
chmod +x "$out"
echo "wrote $out"
