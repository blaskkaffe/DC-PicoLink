static void status(const char *fmt, ...) __attribute__((format(printf, 1, 2)));

#ifndef DC_CONSOLE_BAUD
#define DC_CONSOLE_BAUD (50e6f / (32.0f * 14.0f))   /* SCBRR 13 for 115200 */
#endif
/* ---- mode changes made by core1 --------------------------------------- */
static int seen_mode = MODE_SERIAL;

static void track_mode(void) {
    int m = dc_mode;
    if (m == seen_mode) return;
    static const char *const names[] = { "serial", "SPI (SD/W5500)", "offline (DC off or not started)" };
    status("mode: %s -> %s", names[seen_mode], names[m]);
    seen_mode = m;
    static float saved_baud;
    if (m == MODE_W5500) {            /* listen to the DC's console (KOS: 115200 = 111607 real) */
        saved_baud = wire_baud;
        set_wire_baud(DC_CONSOLE_BAUD);
        rx_rd = rx_written();
    } else if (saved_baud != 0) {
        set_wire_baud(saved_baud);
        saved_baud = 0;
    }
    if (m != MODE_SERIAL) {
        /* serial path is dead (W5500 or DC off): flush everything queued for the DC UART */
        dma_channel_abort(dma_tx);
        pio_sm_clear_fifos(uart_pio, uart_sm_tx);
        pending_baud = 0;
    } else {
        /* back to serial: drop whatever the RX DMA picked up meanwhile */
        rx_rd = rx_written();
        rts_asserted = true;          /* core1 re-asserted RTS */
    }
}

/* ---- DC console while in SPI mode ---------------------------------------
   KOS prints its debug log (dbglog) on the serial port whenever SCIF-SPI is
   shut down, e.g. between the W5500 driver's probe and its init. The UART
   receiver keeps listening in SPI mode; clean text lines are passed to the Pi
   log as "dc console: ...". SPI traffic on the same wire decodes as junk and
   is dropped (a line must be printable from start to end). */
static void console_task(void) {
    static char line[128];
    static uint32_t n, last, sent_t, sent_n;
    static bool junk;
    uint32_t now = time_us_32();
    if (seen_mode != MODE_W5500) { n = 0; junk = false; return; }
    uint32_t w = rx_written();
    if (w - rx_rd > RX_WORDS) rx_rd = w - RX_WORDS / 2;
    for (; rx_rd != w; rx_rd++) {
        uint32_t wd = rx_ring[rx_rd & (RX_WORDS - 1)];
        last = now;
        uint8_t c = rx_ok(wd) ? rx_decode(wd) : 0;
        if (c == '\r') continue;
        if (c == '\n' || n >= sizeof line - 1) {
            if (!junk && n >= 3 && sd_link_up) {
                if (now - sent_t > 1000000u) { sent_t = now; sent_n = 0; }
                if (sent_n++ < 40) { line[n] = 0; status("dc console: %s", line); }
            }
            n = 0; junk = false;
            continue;
        }
        if (c < 0x20 || c > 0x7E) { junk = true; continue; }
        line[n++] = (char)c;
    }
    if (n && now - last > 200000u) {               /* text without a newline */
        if (!junk && n >= 3 && sd_link_up) { line[n] = 0; status("dc console: %s", line); }
        n = 0; junk = false;
    }
}

/* ---- W5500 <-> USB network (CDC-NCM) ----------------------------------- */
static bool net_rx_retry;
static uint32_t net_in, net_in_drop, net_out, net_in_full;

bool tud_network_recv_cb(const uint8_t *src, uint16_t size) {
    if (dc_mode != MODE_W5500 || !w5.sock_open) {
        net_in_drop++;
        net_rx_retry = true;
        return true;
    }
    if (w5_net_rx(src, size)) {
        net_in++;
        net_rx_retry = true;          /* accepted (or dropped): ask for the next one */
        return true;
    }
    net_in_full++;
    net_rx_retry = true;              /* buffer full: retry later */
    return false;
}

uint16_t tud_network_xmit_cb(uint8_t *dst, void *ref, uint16_t arg) {
    (void)arg;
    w5_txd_t *d = (w5_txd_t *)ref;
    uint16_t n = d->len;
    w5_net_tx_copy(d, dst);
    w5_net_tx_pop();
    net_out++;
    return n;
}

void tud_network_init_cb(void) { }

static void net_task(void) {
    w5.link_up = tud_mounted();
    w5_txd_t *d = w5_net_tx_peek();
    if (d) {
        if (!tud_mounted()) w5_net_tx_pop();          /* nobody to send to */
        else if (tud_network_can_xmit(d->len)) tud_network_xmit(d, 0);
    }
    if (net_rx_retry) {
        net_rx_retry = false;
        tud_network_recv_renew();
    }
}

