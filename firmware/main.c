/*
 * RP2040 USB <-> Dreamcast serial ("coder's cable") + W5500 emulator (see README.md)
 * Core0: USB (CDC-ACM serial + CDC-NCM network), UART bridge. Core1: spi_slave.c
 *
 * Wiring (via DC SD Adapter V2, SD-card pin names -> Dreamcast SCIF signal):
 *   GPIO2  SD CLK   = DC CTS  (DC input)  -- sense only; driven from GPIO6 via 1k
 *   GPIO3  SD CMD   = DC TXD  (DC output) -> our RX
 *   GPIO4  SD DAT0  = DC RXD  (DC input)  <- our TX
 *   GPIO5  SD DAT3  = DC RTS  (DC output) -> our CTS (flow control input)
 *   GPIO6  ---[1k]--- GPIO2   our RTS output -> DC CTS
 *   GND    SD VSS   = DC GND
 *
 * The 1k resistor protects against contention: KallistiOS' SD-over-serial driver
 * drives DC CTS as an output (SPI clock). GPIO2 is therefore left as an input.
 *
 * Baud rates: whatever the host requests is generated by PIO. With DC_BAUD_MATCH
 * enabled the rate is rounded exactly like dcload-serial/KOS program the SCIF
 * (SCBRR = 50MHz/(32*baud) - 1, truncated), so the adapter runs at precisely the
 * rate the Dreamcast actually uses (only above 115200; 115200 and below are
 * generated exactly, like FTDI/CP210x adapters): 230400 -> 260416,
 * 500000 -> 520833, 1500000 -> 1562500, and DC-native rates (1562500, 781250,
 * 520833, 390625, 312500, 260416, 223214, 111607...) map to themselves.
 * Above 1562500 dcload's 8-bit divider wraps (0 - 1 = 255): -b 1600000 really
 * puts the DC at 6103 baud, so the cable does the same and logs a hint
 * (baud_model.h).
 */

