static void autobaud_task(void) {
    static uint32_t win[32], wn;
    static float cand;
    static uint32_t cand_n;
    static bool reported;
    static uint32_t fe_count, fe_last_report, fe_reported, fe_mark;
    static int last_mode = -1;
    uint32_t now = time_us_32();

    static uint32_t warned_baud;
    if (baud_wrapped && cur_baud != warned_baud && sd_link_up) {
        warned_baud = cur_baud;
        status("serial: host asked %lu baud; above 1562500 dcload's divider wraps and the DC runs at %.0f baud "
               "(the cable matches it). The DC's fastest rate is 1562500: use -b 1500000 or -b 1562500",
               (unsigned long)cur_baud, (double)wire_baud);
    }
    if (!baud_wrapped) warned_baud = 0;

    static uint32_t spi_since;
    if (seen_mode != last_mode) {             /* new DC session: forget everything */
        /* Forget the learned DC rate when the DC goes offline, or after a real SD
           session (> 1 s of SPI: a loader started another program, which sets its
           own speed). A short SPI blip keeps it. */
        bool forget = seen_mode == MODE_OFFLINE ||
                      (last_mode == MODE_W5500 && seen_mode == MODE_SERIAL && now - spi_since > 1000000u);
        if (seen_mode == MODE_W5500) spi_since = now;
        last_mode = seen_mode;
        wn = 0; cand = 0; reported = false;
        if (auto_baud != 0 && forget) {
            auto_baud = 0;
            set_wire_baud(dc_effective_baud(cur_baud));
            if (seen_mode == MODE_SERIAL) status("serial: new program after SD use, back to host speed %lu", (unsigned long)cur_baud);
        }
    }
    if (seen_mode != MODE_SERIAL) {
        while (!pio_sm_is_rx_fifo_empty(uart_pio, meter_sm)) (void)pio_sm_get(uart_pio, meter_sm);
        return;
    }
    fe_count = rx_fe_count;
    if (fe_count != fe_reported && now - fe_last_report > 5000000u) {
        status("serial: %lu framing errors from the DC so far (wire %.0f baud, host %lu)",
               (unsigned long)fe_count, (double)wire_baud, (unsigned long)cur_baud);
        fe_reported = fe_count; fe_last_report = now;
    }

#if DC_DIAG
    for (uint8_t i = 0; i < ppm_nrep; i++) status("serial: %s", ppm_rep[i]);
    if (ppm_nrep && ppm_rep_dropped) status("serial: (%lu more bad frames not shown)", (unsigned long)ppm_rep_dropped);
    if (ppm_nrep) { ppm_nrep = 0; ppm_rep_dropped = 0; }
    static uint32_t pp_last, pp_good, pp_bad;
    if ((ppm.good != pp_good || ppm.bad != pp_bad) && now - pp_last > 10000000u) {
        status("serial: PPP frames from the DC as received by the cable: %lu good, %lu bad checksum; "
               "split votes in %lu of %lu chars (%lu bits); %lu ring overruns",
               (unsigned long)ppm.good, (unsigned long)ppm.bad, (unsigned long)ppm.split_chars,
               (unsigned long)ppm.chars, (unsigned long)ppm.split_bits, (unsigned long)rx_overruns);
        pp_good = ppm.good; pp_bad = ppm.bad; pp_last = now;
    }
#endif

    while (!pio_sm_is_rx_fifo_empty(uart_pio, meter_sm)) {
        uint32_t cyc = 2u * pio_sm_get(uart_pio, meter_sm) + 4u;
        if (cyc < 40u) continue;                       /* glitch */
        win[wn++] = cyc;
        if (wn < 32) continue;
        wn = 0;
        if (!abw_usable(win, 32)) continue;            /* all pulses equal: a run of zero bytes looks like a slow DC */
        uint32_t m = 0xFFFFFFFFu;
        for (int i = 0; i < 32; i++) if (win[i] < m) m = win[i];
        uint64_t sum = 0; uint32_t cnt = 0;
        for (int i = 0; i < 32; i++) if (win[i] <= m + m / 3) { sum += win[i]; cnt++; }
        if (cnt < 4) continue;
        float bit = (float)sum / (float)cnt;
        uint32_t fit = 0;                              /* pulses ~ whole bit counts? */
        for (int i = 0; i < 32; i++) {
            float q = (float)win[i] / bit, f = q - (float)(int)(q + 0.5f);
            if (fabsf(f) < 0.2f) fit++;
        }
        if (fit < 26) continue;
        float rate = (float)clock_get_hz(clk_sys) / bit;
        float snapped = snap_dc_rate(rate);
        if (!reported) {
            status("serial: DC transmits at ~%.0f baud (nearest SCIF rate %.0f); wire %.0f, host asked %lu",
                   (double)rate, (double)snapped, (double)wire_baud, (unsigned long)cur_baud);
            reported = true;
        }
#if DC_AUTOBAUD
        /* Follow the DC when the current speed is off by more than 2.5%:
           - right away (2 agreeing windows) if framing errors show it's wrong;
           - otherwise only after 4 agreeing windows with plenty of 1-bit pulses
             (a mis-measured window can't re-tune a working link).
           At 4% off (115200 vs the DC's 120192) most bytes still decode, but ~1%
           are damaged: enough to lose most large PPP frames. */
        float off = fabsf(rate / wire_baud - 1.0f);
        if (off < 0.025f || rate > 400000.0f || wire_baud > 400000.0f) { cand = 0; cand_n = 0; continue; }
        if ((int32_t)(now - baud_holdoff_until) < 0) continue;
        bool clean = cnt >= 8;                         /* >= 25% single-bit pulses */
        /* framing errors are counted from the first window of this candidate on,
           so slow traffic (a game retrying "AT" once a second) still adds up */
        if (cand == 0 || fabsf(rate / cand - 1.0f) > 0.015f) { cand = rate; cand_n = 1; fe_mark = fe_count; continue; }
        cand_n++;
        bool errors = fe_count != fe_mark;
        if (ab_fraction(wire_baud, rate) && cand_n < 16) continue;     /* 1/2, 1/3 ... of the wire rate: be sure first */
        if (!(errors && cand_n >= 2) && !(clean && cand_n >= 4)) continue;
        auto_baud = snapped;
        set_wire_baud(snapped);
        cand = 0; cand_n = 0;
        status("serial: following the DC at %.0f baud (host asked %lu)", (double)snapped, (unsigned long)cur_baud);
#endif
    }
}

/* ---- SD card backend (dcsd on the Pi) ------------------------------------ */
static void sd_task(void) {
    /* No DTR on a vendor interface: the link is up while dcsd talks to us (it
       sends 'I' at start and every 2 s), and down after 5 s of silence. */
    static uint32_t last_rx;
    uint32_t now = time_us_32();
    if (!tud_mounted()) {
        if (sd_link_up) { sd_link_up = false; sdh_disconnected(); }
        return;
    }
    uint8_t buf[256];
    uint32_t n;
    while ((n = tud_vendor_available()) > 0) {
        if (n > sizeof buf) n = sizeof buf;
        n = tud_vendor_read(buf, n);
        if (!sd_link_up) { sd_link_up = true; sdh_connected(); }
        last_rx = now;
        sdh_rx(buf, n);
    }
    if (sd_link_up && now - last_rx > 5000000u) { sd_link_up = false; sdh_disconnected(); }
    if (sd_link_up) sdh_poll();
    tud_vendor_write_flush();
}

int main(void) {
#ifdef DC_SYS_KHZ
    /* optional overclock for more SPI reply headroom, e.g. -DDC_SYS_KHZ=250000 */
    vreg_set_voltage(VREG_VOLTAGE_1_20);
    busy_wait_us(1000);
    set_sys_clock_khz(DC_SYS_KHZ, true);
#endif
    serial_init();
    w5500_spi_init();
    cap_init();
    tusb_init();
    multicore_launch_core1(core1_main);
    while (true) {
        tud_task();
        track_mode();
        if (seen_mode == MODE_SERIAL) {
            usb_to_dc();
            dc_to_usb();
        } else {
            uint8_t junk[64];             /* serial port idle in W5500 mode */
            while (tud_cdc_available()) tud_cdc_read(junk, sizeof(junk));
        }
        net_task();
        spi_report();
        console_task();
        hello_task();
        force_task();
        capture_task();
        sd_task();
        autobaud_task();
        power_sense_task();
        sense_report_task();
    }
}
